 test.skip(process.env.PAYMENTS_BUYER_PROOF!=='true'||!['localhost','127.0.0.1'].includes(new URL(baseURL!).hostname),'Explicit local-only readback of the exercised fixture')
 const login=await page.request.post('/api/auth/sign-in/email',{headers:authRequestHeaders(baseURL!),data:{email:'payments-proof-owner@playwright.example',password}})
